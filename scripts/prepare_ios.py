#!/usr/bin/env python3
"""Select and validate iOS identity before flutter build/run; FR-47."""
import argparse
import json
import plistlib
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument("environment", choices=["production", "staging"])
parser.add_argument("--config-root", type=Path, default=root / "env")
args = parser.parse_args()
config = json.loads((args.config_root / f"{args.environment}.json").read_text())
test = args.environment == "staging"
bundle = "blab.nastia.ez.test" if test else "blab.nastia.ez"
channel = "test" if test else "public"
assert config["BLAB_ENV"] == args.environment
assert config.get("BLAB_APP_CHANNEL", "public") == channel
assert (config["SUPABASE_PROJECT_REF"] == "bhzcexhebjszwyqvcsxs") == (not test)
firebase_path = args.config_root / "firebase" / args.environment / "GoogleService-Info.plist"
firebase = plistlib.loads(firebase_path.read_bytes())
assert firebase["BUNDLE_ID"] == bundle
assert firebase["PROJECT_ID"] == config["FIREBASE_PROJECT_ID"]
client = firebase.get("CLIENT_ID", "")
assert client.endswith(".apps.googleusercontent.com"), "Missing iOS Google OAuth client"
reversed_client = ".".join(reversed(client.split(".")))
settings = {
    "BLAB_BUNDLE_ID": bundle,
    "BLAB_DISTRIBUTION_PROFILE": "Blab Test App Store" if test else "Blab Production App Store",
    "BLAB_APP_NAME": "Blab-test" if test else "Blab",
    "BLAB_URL_SCHEME": "blab-test" if test else "blab",
    "BLAB_GOOGLE_CLIENT_ID": client,
    "BLAB_GOOGLE_URL_SCHEME": reversed_client,
}
assert all("\n" not in value for value in settings.values())
(root / "ios/Flutter/BlabEnvironment.xcconfig").write_text(
    "// Generated by scripts/prepare_ios.py; do not commit.\n"
    + "".join(f"{key} = {value}\n" for key, value in settings.items())
)
(root / "ios/Runner/GoogleService-Info.plist").write_bytes(firebase_path.read_bytes())
print(f"Prepared {args.environment} iOS identity: {bundle}")
